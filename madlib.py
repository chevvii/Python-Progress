# word game where you create a story by filling in blanks with random words

adjective1 = input("Enter a random adjective: ")
noun1 = input("Enter a random noun: ")
adjective2 = input("Enter an another random adjective: ")
verb1 = input("Enter a random, in continuous form verb: ")
adjective3 = input("Lastly, enter a random adjective again: ")

print(f"Today, I went to a {adjective1} zoo.")
print(f"In an exhibit, I saw a {noun1}")
print(f"{noun1} was {adjective2} and {verb1}")
print(f"I was {adjective3}!")